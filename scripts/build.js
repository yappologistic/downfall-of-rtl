#!/usr/bin/env node
'use strict';
// Builds every target from src/core.js. No bundler, no dependencies, no RTL.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => {
  fs.writeFileSync(path.join(root, p), s);
  console.log(`  built  ${p}`);
};

const core = read('src/core.js');
const { VERSION } = require('../src/core.js');
const GENERATED = '// GENERATED by scripts/build.js from src/ — edit the source, not this file.\n';

// Wrap core so it doesn't fight CommonJS hosts (Obsidian) over module.exports.
const wrapped = `var DownfallOfRTL = (function () {\n  var module = { exports: {} };\n${core}\n  return module.exports;\n})();\n`;

// 1. Browser extension: plain copy, it attaches to globalThis.
write('extension/core.js', GENERATED + core);

// 2. Userscript (Tampermonkey / Violentmonkey / Greasemonkey).
write(
  'userscript/downfall-of-rtl.user.js',
  `// ==UserScript==
// @name         Downfall of RTL
// @namespace    https://github.com/yappologistic/downfall-of-rtl
// @homepageURL  https://github.com/yappologistic/downfall-of-rtl
// @version      ${VERSION}
// @description  An LTR plugin for the RTL plugins. Forces every site back to left-to-right.
// @match        *://*/*
// @run-at       document-start
// @grant        none
// @noframes
// ==/UserScript==
${GENERATED}
// Pick your fighter: 'polite' | 'spicy' | 'nuclear'
const LEVEL = 'spicy';

${wrapped}
DownfallOfRTL.unleash({ level: LEVEL });
`
);

// 3. Obsidian plugin: one self-contained main.js.
write('obsidian/main.js', GENERATED + wrapped + '\n' + read('obsidian/plugin.src.js'));
